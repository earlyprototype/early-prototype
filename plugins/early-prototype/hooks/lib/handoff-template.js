/**
 * Handoff Template - Render Dev-Lead-SOP §6 skeleton from transcript data.
 *
 * Two outputs:
 *   - renderProjectHandoff: full §6 skeleton, lives at
 *     <project>/session-handover-<DATE>-<TASKSLUG>.md
 *   - renderInboxPointer:    short skim with link to canonical, lives at
 *     ~/.claude/inbox/pm/handoff-<DATE>-<SHORT>-<TASKSLUG>.md
 *
 * Objective sections (files modified, tools used, user messages) filled from
 * the transcript summary. Worker can dictate the "Issues encountered" section
 * deliberately by running /notetime — entries land in <cwd>/.claude/worker-notes.md
 * and this template embeds them (capped at WORKER_NOTES_MAX_CHARS with elision).
 * Other subjective sections (project context, where-we-are, open questions,
 * confabulation) stay [TBD] for Worker fill or PM follow-up. We deliberately
 * do not infer subjective content — see Dev-Lead-SOP §5 #5 ("Never confabulate").
 */

const fs = require('fs');
const path = require('path');

const TBD = '[TBD - Worker should fill before stop, or PM follow-up]';
const WORKER_NOTES_MAX_CHARS = 4096;

function _renderWorkerNotes(worktree) {
  if (!worktree) return TBD;
  const notesPath = path.join(worktree, '.claude', 'worker-notes.md');
  let raw;
  try { raw = fs.readFileSync(notesPath, 'utf8'); }
  catch { return TBD; }
  const trimmed = raw.trim();
  if (!trimmed) return TBD;
  if (trimmed.length <= WORKER_NOTES_MAX_CHARS) return trimmed;
  // Keep the most recent notes; older ones are elided. The full file is
  // always at .claude/worker-notes.md if the reader wants the full history.
  const tail = trimmed.slice(-WORKER_NOTES_MAX_CHARS);
  return `_... (older notes elided; full content in \`.claude/worker-notes.md\`)._\n\n${tail}`;
}

function _kanbanLine(kanbanResult) {
  if (!kanbanResult) return 'kanban: no attempt';
  if (kanbanResult.moved) {
    const where = kanbanResult.kanbanPath ? ` (${kanbanResult.kanbanPath})` : '';
    return `kanban: ${kanbanResult.reason}${where}`;
  }
  return `kanban: skipped - ${kanbanResult.reason}`;
}

function renderProjectHandoff(summary, metadata) {
  const { taskTitle, sessionShortId, date, project, branch, worktree, kanbanResult } = metadata;
  const msgs = (summary && summary.userMessages) || [];
  const tools = (summary && summary.toolsUsed) || [];
  const files = (summary && summary.filesModified) || [];

  const filesBlock = files.length
    ? files.map(f => `- ${f}`).join('\n')
    : '_No file modifications detected in transcript._';
  const fileIndexBlock = files.length
    ? files.map(f => `- \`${f}\``).join('\n')
    : '_No files touched._';
  const toolsBlock = tools.length ? tools.join(', ') : '_None recorded._';
  const msgsBlock = msgs.length
    ? msgs.map(m => `> ${m.replace(/\n/g, ' ')}`).join('\n\n')
    : '_None recorded._';

  return [
    `# Session Handover ${date}`,
    ``,
    `**Worker session ended.** Skeleton produced by \`worker-completion-signal.js\` Stop hook. Worker should fill [TBD] sections before stop, or PM picks up on follow-up.`,
    ``,
    `- **Active task:** ${taskTitle || '[unknown - no .claude/active-task.txt]'}`,
    `- **Session shortId:** ${sessionShortId}`,
    `- **Project:** ${project}`,
    `- **Branch:** ${branch}`,
    `- **Worktree:** ${worktree}`,
    `- **${_kanbanLine(kanbanResult)}**`,
    ``,
    `## Project context`,
    ``,
    TBD,
    ``,
    `## State at start of session`,
    ``,
    TBD,
    ``,
    `## What was built or changed`,
    ``,
    filesBlock,
    ``,
    `## Issues encountered + resolutions`,
    ``,
    _renderWorkerNotes(worktree),
    ``,
    `## Where we are now`,
    ``,
    TBD,
    ``,
    `## Open architectural questions`,
    ``,
    TBD,
    ``,
    `## Confabulation incidents this session`,
    ``,
    TBD,
    ``,
    `## File index`,
    ``,
    fileIndexBlock,
    ``,
    `## Tools used`,
    ``,
    toolsBlock,
    ``,
    `## User messages (last 10)`,
    ``,
    msgsBlock,
    ``,
    `## How to resume`,
    ``,
    TBD,
    ``,
    `---`,
    ``,
    `_Generated by worker-completion-signal.js. Canonical §6 format defined in Dev-Lead-SOP.md._`,
    ``
  ].join('\n');
}

function renderInboxPointer(summary, metadata, projectHandoffPath) {
  const { taskTitle, sessionShortId, date, project, kanbanResult } = metadata;
  const msgs = (summary && summary.userMessages) || [];
  const files = (summary && summary.filesModified) || [];
  const filesPreview = files.length
    ? files.slice(0, 15).map(f => `- ${f}`).join('\n') +
      (files.length > 15 ? `\n_...and ${files.length - 15} more (see canonical)._` : '')
    : '_None._';
  const msgsPreview = msgs.length
    ? msgs.slice(-5).map(m => `> ${m.replace(/\n/g, ' ').slice(0, 200)}`).join('\n\n')
    : '_None recorded._';

  return [
    `# PM Inbox: handoff ${date} (${sessionShortId})`,
    ``,
    `- **Active task:** ${taskTitle || '[unknown]'}`,
    `- **Project:** ${project}`,
    `- **Status:** ${_kanbanLine(kanbanResult)}`,
    `- **Canonical handoff:** \`${projectHandoffPath}\``,
    ``,
    `## Files touched`,
    ``,
    filesPreview,
    ``,
    `## Last user messages`,
    ``,
    msgsPreview,
    ``,
    `---`,
    `_Pointer only. Read the canonical handoff for full §6 sections._`,
    ``
  ].join('\n');
}

module.exports = { renderProjectHandoff, renderInboxPointer };
